export type AuriaIconName = keyof typeof AURIA_ICON_PATHS;

export type AuriaIconProps = {
  name: AuriaIconName;
  size?: number;
  color?: string;
  strokeWidth?: number;
  active?: boolean;
  tertiary?: boolean;
};

export function AuriaIcon({
  name,
  size = AURIA_ICON_SIZE.sm,
  color,
  strokeWidth = AURIA_ICON_STROKE_NAV,
  active = false,
  tertiary = false,
}: AuriaIconProps) {
  const { ds } = useTheme();
  const resolvedColor = useMemo(() => {
    if (color) return color;
    if (active) return ds.gray900;
    if (tertiary) return ds.gray500;
    return ds.gray600;
  }, [active, color, ds.gray500, ds.gray600, ds.gray900, tertiary]);

  return (
    <OutlineIcon
      paths={AURIA_ICON_PATHS[name]}
      size={size}
      color={resolvedColor}
      strokeWidth={strokeWidth}
    />
  );
}

